// Helper to generate 1150 realistic responses distributed across academic years and forms
export function generateSeedResponses(stakeholders: Stakeholder[]): FeedbackResponse[] {
  const responses: FeedbackResponse[] = [];
  const depts = ['dept-1', 'dept-2', 'dept-3', 'dept-4', 'dept-5'];
  const progs = ['prog-1', 'prog-2', 'prog-3', 'prog-4', 'prog-5'];
  const ays = ['ay-5', 'ay-4', 'ay-3']; // Recent years

  const formsByType: Record<string, string[]> = {
    STUDENT: ['form-1', 'form-5', 'form-6', 'form-8', 'form-9', 'form-10'],
    FACULTY: ['form-2', 'form-14'],
    NON_TEACHING: ['form-11', 'form-12'],
    TECHNICAL_STAFF: ['form-13'],
    ALUMNI: ['form-4'],
    EMPLOYER: ['form-3'],
    PARENT: ['form-7'],
  };

  let resId = 1;

  for (let i = 0; i < 1150; i++) {
    const isCurrent = i < 820; // 820 responses for current year
    const ay = isCurrent ? 'ay-5' : i < 1000 ? 'ay-4' : 'ay-3';
    const stakeholder = stakeholders[i % stakeholders.length];
    const availableForms = formsByType[stakeholder.type] || ['form-1'];
    const formId = availableForms[i % availableForms.length];
    const dept = stakeholder.departmentId || depts[i % depts.length];
    const prog = stakeholder.programmeId || progs[i % progs.length];
    const isAnonymous = i % 3 === 0;

    // Realistic score generation with department variance
    const baseScore = 3.7 + ((i * 19) % 13) / 10;
    const overallScore = Math.min(5.0, Math.max(1.0, Math.round(baseScore * 10) / 10));
    const sentimentScore = Math.round((overallScore - 3.0) / 2 * 100) / 100;

    // Sample question answers
    const answers = [
      { questionId: 'q-1-1', scoreValue: Math.min(5, Math.max(1, Math.round(overallScore + ((i % 5) - 2) * 0.2))) },
      { questionId: 'q-1-2', scoreValue: Math.min(5, Math.max(1, Math.round(overallScore + ((i % 3) - 1) * 0.3))) },
      { questionId: 'q-1-4', scoreValue: Math.min(5, Math.max(1, Math.round(overallScore + ((i % 4) - 1.5) * 0.2))) },
    ];

    responses.push({
      id: `resp-${resId++}`,
      formId,
      academicYearId: ay,
      departmentId: dept,
      programmeId: prog,
      stakeholderId: isAnonymous ? undefined : stakeholder.id,
      userId: undefined,
      isAnonymous,
      stakeholderType: stakeholder.type,
      overallScore,
      sentimentScore,
      submittedAt: new Date(Date.now() - (1150 - i) * 3600 * 1000 * 3.5).toISOString(),
      answers,
    });
  }

  return responses;
}
